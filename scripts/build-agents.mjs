#!/usr/bin/env node
// Reads agents/*.md and commands/*.md, inlines the IC Codex into the
// code-reviewer agent's system prompt, and writes src/agents.generated.ts.
// The output module is imported by src/agents.ts and included in the
// /.well-known/opencode discovery payload.

import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseFrontmatter } from "./lib/frontmatter.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const AGENTS_DIR = join(ROOT, "agents");
const COMMANDS_DIR = join(ROOT, "commands");
const RULES_DIR = join(ROOT, "codex", "rules");
const OUTPUT = join(ROOT, "src", "agents.generated.ts");

async function readMarkdownFiles(dir) {
  const entries = (await readdir(dir))
    .filter((name) => name.endsWith(".md"))
    .sort();
  const files = [];
  for (const name of entries) {
    const source = await readFile(join(dir, name), "utf8");
    const parsed = parseFrontmatter(source, name);
    files.push({ name: name.replace(/\.md$/, ""), ...parsed });
  }
  return files;
}

async function loadCodex() {
  const files = (await readdir(RULES_DIR))
    .filter((n) => n.endsWith(".md"))
    .sort();
  const rules = [];
  for (const name of files) {
    const source = await readFile(join(RULES_DIR, name), "utf8");
    const { data, body } = parseFrontmatter(source, name);
    rules.push({
      id: data.id,
      title: data.title,
      severity: data.severity,
      rationale: body,
    });
  }
  return rules;
}

function renderCodex(rules) {
  const lines = [
    "## The IC Codex",
    "",
    `Below is the complete IC Codex — ${rules.length} rules, the reviewer's source of truth.`,
    "Cite rule IDs exactly as written (e.g. `IC-TEST-009`).",
    "",
  ];
  for (const rule of rules) {
    lines.push(
      `### ${rule.id} — ${rule.title} [${rule.severity}]`,
      "",
      rule.rationale,
      "",
    );
  }
  return lines.join("\n").trimEnd();
}

function buildAgent(file, codexSection) {
  const { data, body, name } = file;
  if (!data.description)
    throw new Error(`agents/${name}.md: missing required "description"`);
  if (!body)
    throw new Error(`agents/${name}.md: empty body (no system prompt)`);

  const prompt = `${body}\n\n${codexSection}\n`;
  const config = {
    description: data.description,
    mode: data.mode ?? "subagent",
    prompt,
  };
  if (typeof data.temperature === "number")
    config.temperature = data.temperature;
  if (typeof data.model === "string") config.model = data.model;
  if (typeof data.hidden === "boolean") config.hidden = data.hidden;
  if (data.permission && typeof data.permission === "object")
    config.permission = data.permission;
  return [name, config];
}

function buildCommand(file) {
  const { data, body, name } = file;
  if (!data.description)
    throw new Error(`commands/${name}.md: missing required "description"`);
  if (!body) throw new Error(`commands/${name}.md: empty body (no template)`);

  const config = {
    description: data.description,
    template: body,
  };
  if (typeof data.agent === "string") config.agent = data.agent;
  if (typeof data.subtask === "boolean") config.subtask = data.subtask;
  if (typeof data.model === "string") config.model = data.model;
  return [name, config];
}

async function main() {
  const [rules, agentFiles, commandFiles] = await Promise.all([
    loadCodex(),
    readMarkdownFiles(AGENTS_DIR),
    readMarkdownFiles(COMMANDS_DIR),
  ]);

  const codexSection = renderCodex(rules);

  const agents = Object.fromEntries(
    agentFiles.map((f) => buildAgent(f, codexSection)),
  );
  const commands = Object.fromEntries(commandFiles.map((f) => buildCommand(f)));

  const header = [
    "// This file is generated by scripts/build-agents.mjs. Do not edit by hand.",
    "// Regenerate with: npm run build:agents",
    "",
    "export type AgentConfig = Record<string, Record<string, unknown>>;",
    "export type CommandConfig = Record<string, Record<string, unknown>>;",
    "",
    "export const AGENTS: AgentConfig = ",
  ].join("\n");

  const agentsJson = JSON.stringify(agents, null, "\t") + ";\n";
  const commandsPart =
    "\nexport const COMMANDS: CommandConfig = " +
    JSON.stringify(commands, null, "\t") +
    ";\n";

  await writeFile(OUTPUT, header + agentsJson + commandsPart);

  console.log(
    `Wrote ${Object.keys(agents).length} agent(s) and ${Object.keys(commands).length} command(s) to ${OUTPUT.replace(ROOT + "/", "")}`,
  );
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});

#!/usr/bin/env node
// Reads codex/rules/*.md, parses frontmatter, and writes src/codex.generated.ts.
// The output module is imported by src/codex.ts and served at /.well-known/codex.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFrontmatter } from './lib/frontmatter.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RULES_DIR = join(ROOT, 'codex', 'rules');
const OUTPUT = join(ROOT, 'src', 'codex.generated.ts');

const CATEGORIES = new Set(['architecture', 'code', 'testing']);
const SEVERITIES = new Set(['critical', 'important', 'suggestion', 'nit']);

function validateRule({ data, body }, file) {
	for (const field of ['id', 'title', 'category', 'severity']) {
		if (!data[field]) throw new Error(`${file}: missing required frontmatter field "${field}"`);
	}
	if (!/^IC-[A-Z]+-\d{3}$/.test(data.id)) {
		throw new Error(`${file}: id "${data.id}" must match IC-<PREFIX>-<NNN>`);
	}
	if (!CATEGORIES.has(data.category)) {
		throw new Error(`${file}: category "${data.category}" must be one of ${[...CATEGORIES].join(', ')}`);
	}
	if (!SEVERITIES.has(data.severity)) {
		throw new Error(`${file}: severity "${data.severity}" must be one of ${[...SEVERITIES].join(', ')}`);
	}
	if (!body) throw new Error(`${file}: rationale body is empty`);
}

async function main() {
	const entries = (await readdir(RULES_DIR)).filter((name) => name.endsWith('.md')).sort();
	const rules = [];
	const seen = new Set();

	for (const name of entries) {
		const file = join(RULES_DIR, name);
		const source = await readFile(file, 'utf8');
		const parsed = parseFrontmatter(source, name);
		validateRule(parsed, name);

		if (seen.has(parsed.data.id)) throw new Error(`${name}: duplicate id ${parsed.data.id}`);
		seen.add(parsed.data.id);

		rules.push({
			id: parsed.data.id,
			title: parsed.data.title,
			category: parsed.data.category,
			severity: parsed.data.severity,
			source: parsed.data.source,
			rationale: parsed.body,
		});
	}

	const header = [
		'// This file is generated by scripts/build-codex.mjs. Do not edit by hand.',
		'// Regenerate with: npm run build:codex',
		'',
		"export type CodexCategory = 'architecture' | 'code' | 'testing';",
		"export type CodexSeverity = 'critical' | 'important' | 'suggestion' | 'nit';",
		'',
		'export type CodexRule = {',
		'\tid: string;',
		'\ttitle: string;',
		'\tcategory: CodexCategory;',
		'\tseverity: CodexSeverity;',
		'\tsource?: string;',
		'\trationale: string;',
		'};',
		'',
		'export const CODEX_RULES: readonly CodexRule[] = ',
	].join('\n');

	const body = JSON.stringify(rules, null, '\t') + ';\n';
	await writeFile(OUTPUT, header + body);

	console.log(`Wrote ${rules.length} rules to ${OUTPUT.replace(ROOT + '/', '')}`);
}

main().catch((err) => {
	console.error(err.message);
	process.exit(1);
});
